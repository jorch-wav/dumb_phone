def swap_for(theme):
    void, cell, lit, fg, dim, rule, acc = THEMES[theme]
    return {0xFF292E33: void, 0xFF373C41: cell, 0xFF474C51: lit, 0xFF484C4F: lit, 0xFF5B5F62: rule,
            0xFF347BAC: dim, 0xFF4C85E4: acc, 0xFF5E97F6: acc,
            0xFFC2C3C4: fg, 0xFFC3C5C6: fg, 0xFFD4D5D6: fg, 0xFF888888: dim}

def main(src, dst, theme="phosphor"):
    global SWAP
    SWAP = swap_for(theme)
    zin = zipfile.ZipFile(src)
    data = bytearray(zin.read("resources.arsc"))
    n = 0
    for old, new in SWAP.items():
        o, w = struct.pack("<I", old), struct.pack("<I", new)
        i = data.find(o)
        while i >= 0:
            # Res_value: size(2)=8, res0(1)=0, dataType(1), data(4): only touch colour types 0x1c-0x1f
            if i >= 4 and data[i-4:i-2] == b"\x08\x00" and 0x1c <= data[i-1] <= 0x1f:
                data[i:i+4] = w; n += 1
            i = data.find(o, i + 1)
    with zipfile.ZipFile(dst, "w") as zout:
        for info in zin.infolist():
            if info.filename.startswith("META-INF/"):
                continue                                  # old signature: re-signed later
            body = bytes(data) if info.filename == "resources.arsc" else zin.read(info)
            ni = zipfile.ZipInfo(info.filename, info.date_time)
            ni.compress_type = zipfile.ZIP_STORED if info.filename == "resources.arsc" or info.compress_type == zipfile.ZIP_STORED else zipfile.ZIP_DEFLATED
            ni.external_attr = info.external_attr
            zout.writestr(ni, body)
    print(f"recoloured {n} colour values")

if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2], sys.argv[3] if len(sys.argv) > 3 else "phosphor")
